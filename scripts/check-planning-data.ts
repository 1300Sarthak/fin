/** Synthetic isolated integration check. Never opens the user's finance database. */
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { strict as assert } from "node:assert";
import { migrate } from "drizzle-orm/libsql/migrator";
import ExcelJS from "exceljs";

const directory = await mkdtemp(join(tmpdir(), "finance-planning-check-"));
process.env.DATABASE_URL = `file:${join(directory, "synthetic.db")}`;
try {
  const { db } = await import("../src/db");
  await migrate(db, { migrationsFolder: fileURLToPath(new URL("../drizzle", import.meta.url)) });
  const { accounts } = await import("../src/db/schema");
  await db.insert(accounts).values({ name: "Synthetic checking", type: "checking", currentBalanceCents: 500_000, externalId: "private-provider-id-example" });
  const { getFinancialPlanningContext, savePlanningProfile } = await import("../src/lib/financial-planning");
  const { saveSpreadsheet, updateSpreadsheet, listSpreadsheets, deleteSpreadsheet } = await import("../src/lib/spreadsheets");
  const { setConfig } = await import("../src/lib/config");
  const { exportFinanceXlsx } = await import("../src/lib/export-data");
  await setConfig("simplefin_access_url", "synthetic-secret-must-not-export");
  await setConfig("future_unknown_secret", "synthetic-other-secret-must-not-export");
  await savePlanningProfile({ monthlyTakeHome: 5000, monthlyEssentials: 2000, notes: "Synthetic planning note", tax: { wagesBox1: 60000 } });
  const upload = await saveSpreadsheet(Buffer.from("Item,Amount\nExample groceries,100\nExample utilities,50"), "synthetic.csv");
  let context = await getFinancialPlanningContext({ forAgent: true });
  assert.equal(context.profile, null);
  assert.equal(context.tax, null);
  assert.equal(context.uploads.length, 0);
  await updateSpreadsheet(upload.id, true);
  context = await getFinancialPlanningContext({ forAgent: true });
  assert.equal(context.uploads.length, 1);
  assert.equal(context.profile, null);
  const local = await getFinancialPlanningContext();
  assert.equal(local.profile?.monthlyTakeHome, 5000);
  assert.equal(local.plan?.monthlyRemaining, 3000);
  await savePlanningProfile({ ...local.profile, shareWithAgent: true });
  context = await getFinancialPlanningContext({ forAgent: true });
  assert.equal(context.profile?.monthlyTakeHome, 5000);
  assert.equal(context.tax?.ordinaryIncomeTaxBeforeCredits, 5020);
  await updateSpreadsheet(upload.id, false);
  assert.equal((await listSpreadsheets({ forAgent: true })).length, 0);
  const buffer = await exportFinanceXlsx();
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.load(buffer as unknown as Parameters<typeof workbook.xlsx.load>[0]);
  const cells: unknown[] = [];
  for (const sheet of workbook.worksheets) sheet.eachRow(row => cells.push(row.values));
  const text = JSON.stringify(cells);
  assert(text.includes("Synthetic checking"));
  assert(text.includes("Synthetic planning note"));
  assert(text.includes("Example groceries"));
  assert(!text.includes("synthetic-secret-must-not-export"));
  assert(!text.includes("synthetic-other-secret-must-not-export"));
  assert(!text.includes("private-provider-id-example"));
  assert(workbook.worksheets.some(sheet => sheet.name === "Tax inputs"));
  await deleteSpreadsheet(upload.id);
  assert.equal((await listSpreadsheets()).length, 0);
  const execute = promisify(execFile);
  const cli = async (args: string[]) => {
    const { stdout } = await execute(process.execPath, ["--conditions", "react-server", fileURLToPath(new URL("../cli/fin.ts", import.meta.url)), ...args, "--json"], { env: process.env });
    return JSON.parse(stdout);
  };
  const profilePath = join(directory, "profile.json");
  await writeFile(profilePath, JSON.stringify({ monthlyFlexible: 250 }));
  const saved = await cli(["plan", "set", "--file", profilePath]);
  assert.equal(saved.profile.monthlyFlexible, 250);
  assert.equal(saved.profile.monthlyTakeHome, 5000);
  assert.equal((await cli(["plan"])).plan.monthlyRemaining, 2750);
  assert.equal((await cli(["plan", "schema"])).type, "object");
  assert.equal((await cli(["taxes"])).ordinaryIncomeTaxBeforeCredits, 5020);
  const csvPath = join(directory, "cli-budget.csv");
  await writeFile(csvPath, "Item,Amount\nSynthetic groceries,50");
  const imported = await cli(["import", csvPath]);
  assert.equal(imported.upload.shareWithAgent, false);
  assert.equal((await cli(["spreadsheets", "list", "--for-agent"])).length, 0);
  await cli(["spreadsheets", "share", imported.upload.id]);
  assert.equal((await cli(["spreadsheets", "list", "--for-agent"])).length, 1);
  const exportPath = join(directory, "cli-export.xlsx");
  const exported = await cli(["export", "--out", exportPath]);
  assert.equal(exported.includesCredentials, false);
  assert.equal((await readFile(exportPath)).subarray(0, 2).toString(), "PK");
  await assert.rejects(() => cli(["export", "--out", exportPath]), "Exports should not overwrite existing files without --force.");
  await cli(["spreadsheets", "remove", imported.upload.id]);
  assert.equal((await cli(["spreadsheets"])).length, 0);
  const planningRoute = await import("../src/app/api/planning/route");
  const spreadsheetRoute = await import("../src/app/api/spreadsheets/route");
  const invalidPlan = await planningRoute.POST(new Request("http://localhost/api/planning", { method: "POST", body: JSON.stringify({ monthlyTakeHome: -1 }) }));
  assert.equal(invalidPlan.status, 400);
  const oversizedPlan = await planningRoute.POST(new Request("http://localhost/api/planning", { method: "POST", body: "x".repeat(20_001) }));
  assert.equal(oversizedPlan.status, 413);
  const form = new FormData(); form.append("file", new File(["Item,Amount\nExample,12"], "route.csv"));
  const importResponse = await spreadsheetRoute.POST(new Request("http://localhost/api/spreadsheets", { method: "POST", body: form }));
  assert.equal(importResponse.status, 200);
  const importedFromRoute = await importResponse.json();
  assert.equal(importedFromRoute.upload.shareWithAgent, false);
  assert.equal(importedFromRoute.upload.summaries[0].rowCount, 1);
  assert.equal("sheets" in importedFromRoute.upload, false);
  await deleteSpreadsheet(importedFromRoute.upload.id);
  console.log(`Planning persistence, AI consent, deletion, CLI/API commands, and XLSX privacy checks passed (${workbook.worksheets.length} worksheets; synthetic data only).`);
} finally {
  await rm(directory, { recursive: true, force: true });
}
